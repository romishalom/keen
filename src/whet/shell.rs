//! Shell integration: the `env` script, and an idempotent, removable block in profile files.

use std::path::{Path, PathBuf};

pub const BEGIN: &str = "# >>> keen (whet) >>>";
pub const END: &str = "# <<< keen (whet) <<<";

fn sh_escape(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        if matches!(c, '\\' | '"' | '$' | '`') {
            o.push('\\');
        }
        o.push(c);
    }
    o
}

/// How the install dir is spelled inside double quotes in a shell script.
pub fn home_expr(home: &Path, user_home: &Path) -> String {
    match home.strip_prefix(user_home) {
        Ok(rest) if !user_home.as_os_str().is_empty() => {
            let r = rest.to_string_lossy().replace('\\', "/");
            if r.is_empty() {
                "$HOME".to_string()
            } else {
                format!("$HOME/{}", sh_escape(&r))
            }
        }
        _ => sh_escape(&home.to_string_lossy()),
    }
}

/// `<home>/env`, sourced by login shells.
pub fn env_script(home_expr: &str) -> String {
    format!(
        r#"#!/bin/sh
# keen shell setup (generated by whet; safe to source more than once)
case ":${{PATH}}:" in
    *:"{h}/bin":*) ;;
    *) export PATH="{h}/bin:$PATH" ;;
esac
if [ -n "${{BASH_VERSION:-}}" ] && [ -r "{h}/share/completions/keen.bash" ]; then
    . "{h}/share/completions/keen.bash"
fi
if [ -n "${{ZSH_VERSION:-}}" ] && [ -d "{h}/share/zsh/site-functions" ]; then
    fpath=("{h}/share/zsh/site-functions" $fpath)
fi
"#,
        h = home_expr
    )
}

pub fn source_block(home_expr: &str) -> String {
    format!("{}\n. \"{}/env\"\n{}\n", BEGIN, home_expr, END)
}

pub fn fish_script(bin_dir: &str) -> String {
    format!(
        "# keen shell setup (generated by whet)\nif not contains -- \"{b}\" $PATH\n    set -gx PATH \"{b}\" $PATH\nend\n",
        b = bin_dir.replace('"', "\\\"")
    )
}

/// Insert or refresh the block. Returns true if the file changed.
pub fn add_block(file: &Path, block: &str) -> Result<bool, String> {
    let old = std::fs::read_to_string(file).unwrap_or_default();
    let new = if let (Some(b), Some(e)) = (old.find(BEGIN), old.find(END)) {
        if e < b {
            return Err(format!("`{}` has a damaged keen block; fix or remove it by hand", file.display()));
        }
        let end = e + END.len();
        let end = if old[end..].starts_with('\n') { end + 1 } else { end };
        format!("{}{}{}", &old[..b], block, &old[end..])
    } else {
        let mut t = old.clone();
        if !t.is_empty() && !t.ends_with('\n') {
            t.push('\n');
        }
        if !t.is_empty() {
            t.push('\n');
        }
        t.push_str(block);
        t
    };
    if new == old {
        return Ok(false);
    }
    if let Some(parent) = file.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    std::fs::write(file, new).map_err(|e| format!("cannot write `{}`: {}", file.display(), e))?;
    Ok(true)
}

/// Remove the block (and the blank line added before it). Returns true if the file changed.
pub fn remove_block(file: &Path) -> Result<bool, String> {
    let Ok(old) = std::fs::read_to_string(file) else { return Ok(false) };
    let (Some(b), Some(e)) = (old.find(BEGIN), old.find(END)) else { return Ok(false) };
    if e < b {
        return Ok(false);
    }
    let mut end = e + END.len();
    if old[end..].starts_with('\n') {
        end += 1;
    }
    let mut start = b;
    if old[..start].ends_with("\n\n") {
        start -= 1;
    } else if old[..start].is_empty() && old[end..].starts_with('\n') {
        end += 1;
    }
    let new = format!("{}{}", &old[..start], &old[end..]);
    std::fs::write(file, new).map_err(|e| format!("cannot write `{}`: {}", file.display(), e))?;
    Ok(true)
}

pub fn user_home() -> PathBuf {
    std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map(PathBuf::from)
        .unwrap_or_default()
}

/// POSIX-style profile files to edit: `.profile` always, the others if they exist (or match $SHELL).
pub fn sh_profiles(user_home: &Path, shell: &str) -> Vec<PathBuf> {
    let mut v = vec![user_home.join(".profile")];
    let bashrc = user_home.join(".bashrc");
    if bashrc.exists() || shell.ends_with("bash") {
        v.push(bashrc);
    }
    let bp = user_home.join(".bash_profile");
    if bp.exists() {
        v.push(bp);
    }
    let zdot = std::env::var_os("ZDOTDIR").map(PathBuf::from).unwrap_or_else(|| user_home.to_path_buf());
    let zshenv = zdot.join(".zshenv");
    if zshenv.exists() || shell.ends_with("zsh") {
        v.push(zshenv);
    }
    v
}

pub fn fish_dir(user_home: &Path) -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| user_home.join(".config"));
    base.join("fish")
}

pub fn uses_fish(user_home: &Path, shell: &str) -> bool {
    shell.ends_with("fish") || fish_dir(user_home).is_dir()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("whet-shell-{}-{}", name, std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn home_expression_prefers_home_variable() {
        assert_eq!(home_expr(Path::new("/home/a/.keen"), Path::new("/home/a")), "$HOME/.keen");
        assert_eq!(home_expr(Path::new("/opt/keen"), Path::new("/home/a")), "/opt/keen");
        assert_eq!(home_expr(Path::new("/opt/we\"ird$x"), Path::new("/home/a")), "/opt/we\\\"ird\\$x");
    }

    #[test]
    fn block_is_added_once_preserved_and_removed() {
        let d = tmp("block");
        let f = d.join(".profile");
        std::fs::write(&f, "export A=1\nalias ll='ls -l'").unwrap();
        let block = source_block("$HOME/.keen");
        assert!(add_block(&f, &block).unwrap());
        assert!(!add_block(&f, &block).unwrap(), "second add is a no-op");
        let text = std::fs::read_to_string(&f).unwrap();
        assert_eq!(text.matches(BEGIN).count(), 1);
        assert!(text.starts_with("export A=1\nalias ll='ls -l'\n\n# >>> keen"), "{}", text);
        assert!(remove_block(&f).unwrap());
        assert_eq!(std::fs::read_to_string(&f).unwrap(), "export A=1\nalias ll='ls -l'\n");
        assert!(!remove_block(&f).unwrap());
    }

    #[test]
    fn block_in_a_fresh_file_leaves_it_empty_when_removed() {
        let d = tmp("fresh");
        let f = d.join(".profile");
        add_block(&f, &source_block("$HOME/.keen")).unwrap();
        remove_block(&f).unwrap();
        assert_eq!(std::fs::read_to_string(&f).unwrap(), "");
    }

    #[test]
    fn changed_home_rewrites_the_block_in_place() {
        let d = tmp("rewrite");
        let f = d.join(".bashrc");
        std::fs::write(&f, "before\n").unwrap();
        add_block(&f, &source_block("$HOME/.keen")).unwrap();
        assert!(add_block(&f, &source_block("/opt/keen")).unwrap());
        let text = std::fs::read_to_string(&f).unwrap();
        assert!(text.contains("/opt/keen/env") && !text.contains("$HOME/.keen/env"), "{}", text);
        assert_eq!(text.matches(BEGIN).count(), 1);
    }

    #[test]
    fn env_script_is_idempotent_shell() {
        let s = env_script("$HOME/.keen");
        assert!(s.contains("*:\"$HOME/.keen/bin\":*) ;;"), "{}", s);
        assert!(s.starts_with("#!/bin/sh"));
    }
}
